#!/usr/bin/env python3
"""Generate the app's string accessors and gettext catalogs from its one
catalog, or check that what is committed is what the catalog produces.

    python3 scripts/gen-l10n.py            # write everything below
    python3 scripts/gen-l10n.py --check    # fail if any of it is stale (CI)

The catalog is crates/district-app/l10n/linux.toml (the format is in
tools/l10n/l10n.py's header and the i18n README it names). From it,
tools/l10n/l10n.py writes:

  crates/district-app/src/l10n/text.rs   the Rust accessors, one per key, in
                                         the core's Locale (`--backend rust`)
  crates/district-app/po/district-ai.pot the template catalog GtkBuilder's
  crates/district-app/po/fr.po           lookups use, keyed by `context`
                                         (`--backend po`)
  crates/district-app/tests/generated/accessors.rs
                                         every accessor called in both
                                         languages and held to its catalog's
                                         text (src/l10n.rs includes it in the
                                         unit tests, unformatted)

`--check` also verifies tools/l10n/ against its SHA256SUMS (`l10n.py vendor
--check`), so the vendored tools are the monorepo's, unedited. The test
`l10n::templates` in the app holds every `.ui` string to the .pot's English
for its key.

Python 3.11 or newer, standard library only.
"""

from __future__ import annotations

import importlib.util
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOOL = ROOT / "tools" / "l10n" / "l10n.py"
CATALOG = ROOT / "crates" / "district-app" / "l10n" / "linux.toml"
RUST = ROOT / "crates" / "district-app" / "src" / "l10n" / "text.rs"
PO = ROOT / "crates" / "district-app" / "po"
ACCESSORS = ROOT / "crates" / "district-app" / "tests" / "generated" / "accessors.rs"
OPTS = ("--opt", "locale_path=district_core::Locale", "--opt", "name=district-ai")
HEADER = "// @generated by scripts/gen-l10n.py from crates/district-app/l10n/linux.toml. Do not edit; run the script."


def load_tool():
    spec = importlib.util.spec_from_file_location("l10n", TOOL)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def rust_str(text: str) -> str:
    return '"' + L10N.escape_c_like(text, "rust") + '"'


def expected(entry, lang: str, forms, values: dict) -> str:
    """What the accessor returns for `values`, where `lang`'s plural rules
    choose among `forms`. Numbers are written as plain digits: the app passes
    no number format to the generator."""
    if isinstance(forms, dict):
        category = L10N.plural_category(lang, values[entry.selector()])
        text = forms.get(category, forms["other"])
    else:
        text = forms
    out = []
    for kind, part in L10N.parse_text(text)[0]:
        out.append(part if kind == "lit" else str(values[part]))
    return "".join(out)


def call(entry, locale: str, values: dict) -> str:
    args = [f"Locale::{locale}"]
    for name, kind in entry.args.items():
        args.append(str(values[name]) if kind == "int" else rust_str(values[name]))
    return f"text::{L10N.rust_name(entry)}({', '.join(args)})"


def accessor_test() -> str:
    cats = L10N.load_valid([str(CATALOG)])
    entries = sorted(L10N.all_entries(cats), key=lambda e: e.segs)
    lines = [HEADER, "", "use crate::l10n::{Locale, text};", ""]
    lines.append("#[test]")
    lines.append("fn every_accessor_says_what_the_catalog_says() {")
    for e in entries:
        counts = [1, 7, 0, 1_000_000] if e.plural else [1_204]
        for n in counts:
            values = {name: (n if kind == "int" else "{" + name + "}") for name, kind in e.args.items()}
            en = expected(e, "en", e.en, values)
            fr_lang, fr_forms = ("fr", e.fr) if e.fr is not None else ("en", e.en)
            fr = expected(e, fr_lang, fr_forms, values)
            for locale, text in (("En", en), ("FrCa", fr)):
                lines.append(f"    assert_eq!({call(e, locale, values)}, {rust_str(text)});")
    lines.append("}")
    lines.append("")
    lines.append("#[test]")
    lines.append("fn french_is_complete_only_when_every_entry_has_it() {")
    complete = all(e.fr is not None or e.fixed for e in entries)
    lines.append(f"    assert!({'' if complete else '!'}std::hint::black_box(text::FR_COMPLETE));")
    lines.append("}")
    return "\n".join(lines) + "\n"


L10N = load_tool()


def run(*args: str) -> int:
    return subprocess.run([sys.executable, str(TOOL), *args], cwd=ROOT).returncode


def main(argv: list[str]) -> int:
    if argv not in ([], ["--check"]):
        print(__doc__, file=sys.stderr)
        return 2
    if argv == ["--check"]:
        failed = run("vendor", "--dest", str(TOOL.parent), "--check")
        failed |= run(
            "check",
            str(CATALOG),
            "--gen",
            f"rust:{RUST}",
            "--gen",
            f"po:{PO}",
            *OPTS,
        )
        if not failed and ACCESSORS.read_text(encoding="utf-8") != accessor_test():
            print(f"{ACCESSORS.relative_to(ROOT)} differs from what the catalog produces (run scripts/gen-l10n.py)")
            failed = 1
        return 1 if failed else 0
    failed = run("fmt", str(CATALOG))
    failed |= run("gen", "--backend", "rust", "--out", str(RUST), "--opt", OPTS[1], str(CATALOG))
    failed |= run("gen", "--backend", "po", "--out", str(PO), "--opt", OPTS[3], str(CATALOG))
    if not failed:
        ACCESSORS.parent.mkdir(parents=True, exist_ok=True)
        ACCESSORS.write_text(accessor_test(), encoding="utf-8")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
