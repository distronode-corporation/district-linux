#!/usr/bin/env python3
"""Generate the app's string accessors and gettext catalogs from its
catalogs, or check that what is committed is what the catalogs produce.

    python3 scripts/gen-l10n.py            # write everything below
    python3 scripts/gen-l10n.py --check    # fail if any of it is stale (CI)

The catalogs are crates/district-app/l10n/linux.toml and, for the booking
pages' sections, crates/district-app/l10n/scheduling.toml (the format is in
tools/l10n/l10n.py's header and the i18n README it names). A key is unique
across the two, and both are given together to every command, so what they
produce is one set of accessors and one pair of gettext catalogs. From them,
tools/l10n/l10n.py writes:

  crates/district-app/src/l10n/text.rs   the Rust accessors, one per key, in
                                         the core's Locale (`--backend rust`)
  crates/district-app/po/district-ai.pot the template catalog GtkBuilder's
  crates/district-app/po/fr.po           lookups use, keyed by `context`
                                         (`--backend po`)
  crates/district-app/tests/generated/accessors.rs
                                         every accessor called in both
                                         languages and held to its catalog's
                                         text (src/l10n.rs includes it in the
                                         unit tests, unformatted)

  crates/district-app/data/com.distronode.DistrictAI.metainfo.xml
  crates/district-app/data/com.distronode.DistrictAI.desktop
                                         the AppStream metadata and the desktop
                                         entry, from their `.in` templates and
                                         the catalog's metainfo.* and desktop.*
                                         keys, in English only

    python3 scripts/gen-l10n.py --french-metadata DIR

writes the same two files into DIR with the catalog's French beside the
English (`xml:lang="fr"` elements, `Name[fr]=` keys) wherever an entry has
French. The packages install those only with French on
(scripts/french-enabled.py), so a French-off build's files stay English.

`--check` also verifies tools/l10n/ against its SHA256SUMS (`l10n.py vendor
--check`), so the vendored tools are the monorepo's, unedited. The test
`l10n::templates` in the app holds every `.ui` string to the .pot's English
for its key.

Python 3.11 or newer, standard library only.
"""

from __future__ import annotations

import importlib.util
import re
import subprocess
import sys
import textwrap
from pathlib import Path
from xml.sax.saxutils import escape as xml_escape

ROOT = Path(__file__).resolve().parent.parent
TOOL = ROOT / "tools" / "l10n" / "l10n.py"
CATALOGS = [
    ROOT / "crates" / "district-app" / "l10n" / name for name in ("linux.toml", "scheduling.toml")
]
RUST = ROOT / "crates" / "district-app" / "src" / "l10n" / "text.rs"
PO = ROOT / "crates" / "district-app" / "po"
ACCESSORS = ROOT / "crates" / "district-app" / "tests" / "generated" / "accessors.rs"
DATA = ROOT / "crates" / "district-app" / "data"
# The metadata written from a template, by the name it is installed under.
METADATA = ("com.distronode.DistrictAI.metainfo.xml", "com.distronode.DistrictAI.desktop")
# The column the AppStream description's text wraps at.
WRAP = 80
OPTS = (
    "--opt",
    "locale_path=district_core::Locale",
    "--opt",
    "name=district-ai",
    "--opt",
    "int_fmt=district_core::l10n::format::integer",
)
HEADER = "// @generated by scripts/gen-l10n.py from crates/district-app/l10n/*.toml. Do not edit; run the script."


def load_tool():
    spec = importlib.util.spec_from_file_location("l10n", TOOL)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def rust_str(text: str) -> str:
    return '"' + L10N.escape_c_like(text, "rust") + '"'


def integer(locale: str, n: int) -> str:
    """district_core::l10n::format::integer, the `int_fmt` the accessors use:
    plain digits in English, grouped by no-break spaces in French."""
    digits = str(abs(n))
    if locale == "FrCa":
        digits = "".join(
            ("\u00a0" if i and (len(digits) - i) % 3 == 0 else "") + d for i, d in enumerate(digits)
        )
    return ("-" if n < 0 else "") + digits


def expected(entry, locale: str, lang: str, forms, values: dict) -> str:
    """What the accessor returns in `locale` for `values`, where `lang`'s plural
    rules choose among `forms`."""
    if isinstance(forms, dict):
        category = L10N.plural_category(lang, values[entry.selector()])
        text = forms.get(category, forms["other"])
    else:
        text = forms
    out = []
    for kind, part in L10N.parse_text(text)[0]:
        if kind == "lit":
            out.append(part)
        elif isinstance(values[part], int):
            out.append(integer(locale, values[part]))
        else:
            out.append(values[part])
    return "".join(out)


def call(entry, locale: str, values: dict) -> str:
    args = [f"Locale::{locale}"]
    for name, kind in entry.args.items():
        args.append(str(values[name]) if kind == "int" else rust_str(values[name]))
    return f"text::{L10N.rust_name(entry)}({', '.join(args)})"


def accessor_test() -> str:
    cats = L10N.load_valid([str(path) for path in CATALOGS])
    entries = sorted(L10N.all_entries(cats), key=lambda e: e.segs)
    lines = [HEADER, "", "use crate::l10n::{Locale, text};", ""]
    lines.append("#[test]")
    lines.append("fn every_accessor_says_what_the_catalog_says() {")
    for e in entries:
        counts = [1, 7, 0, 1_000_000] if e.plural else [1_204]
        for n in counts:
            values = {name: (n if kind == "int" else "{" + name + "}") for name, kind in e.args.items()}
            en = expected(e, "En", "en", e.en, values)
            fr_lang, fr_forms = ("fr", e.fr) if e.fr is not None else ("en", e.en)
            fr = expected(e, "FrCa", fr_lang, fr_forms, values)
            for locale, text in (("En", en), ("FrCa", fr)):
                lines.append(f"    assert_eq!({call(e, locale, values)}, {rust_str(text)});")
    lines.append("}")
    lines.append("")
    lines.append("#[test]")
    lines.append("fn french_is_complete_only_when_every_entry_has_it() {")
    complete = all(e.fr is not None or e.fixed for e in entries)
    lines.append(f"    assert!({'' if complete else '!'}std::hint::black_box(text::FR_COMPLETE));")
    lines.append("}")
    return "\n".join(lines) + "\n"


def metadata_text(name: str, french: bool) -> str:
    """`name` written from DATA/`name`.in: each `@key@` placeholder becomes
    the catalog's English for that key, and, with `french`, its French
    beside it wherever the entry has any."""
    cats = L10N.load_valid([str(path) for path in CATALOGS])
    entries = {e.key: e for e in L10N.all_entries(cats)}
    template = (DATA / f"{name}.in").read_text(encoding="utf-8")

    def entry(key: str):
        if key not in entries:
            raise SystemExit(f"{name}.in names {key}, which no catalog has")
        e = entries[key]
        fr = e.fr if french and not e.fixed else None
        return e.en, fr

    out = []
    if name.endswith(".desktop"):
        out.append("# Written by scripts/gen-l10n.py from the .in template beside it and the")
        out.append("# catalog's desktop.* keys: edit those, not this file.")
        for line in template.split("\n"):
            m = re.fullmatch(r"([A-Za-z]+)=@([\w.]+)@", line)
            if not m:
                out.append(line)
                continue
            field, key = m.groups()
            en, fr = entry(key)
            out.append(f"{field}={en}")
            if fr is not None:
                out.append(f"{field}[fr]={fr}")
        return "\n".join(out)
    for line in template.split("\n"):
        m = re.fullmatch(r"(\s*)<(\w+)>@([\w.]+)@</\2>", line)
        if not m:
            out.append(line)
            if line.startswith("<!-- Copyright"):
                out.append(
                    "<!-- Written by scripts/gen-l10n.py from the .in template beside it and\n"
                    "     the catalog's metainfo.* keys: edit those, not this file. -->"
                )
            continue
        indent, tag, key = m.groups()
        en, fr = entry(key)
        for lang, text in (("", en), (' xml:lang="fr"', fr)):
            if text is None:
                continue
            text = xml_escape(text)
            if tag == "p":
                out.append(f"{indent}<p{lang}>")
                out.extend(wrap(text, indent + "  ", indent + "  "))
                out.append(f"{indent}</p>")
            elif tag == "li":
                out.extend(wrap(f"<li{lang}>{text}</li>", indent, indent + "  "))
            elif tag == "keywords":
                if not lang:
                    out.append(f"{indent}<keywords>")
                out.extend(f"{indent}  <keyword{lang}>{word}</keyword>" for word in text.split(", "))
            else:
                out.append(f"{indent}<{tag}{lang}>{text}</{tag}>")
        if tag == "keywords":
            out.append(f"{indent}</keywords>")
    return "\n".join(out)


def wrap(text: str, first: str, rest: str) -> list[str]:
    return textwrap.wrap(
        text,
        WRAP,
        initial_indent=first,
        subsequent_indent=rest,
        break_on_hyphens=False,
        break_long_words=False,
    )


L10N = load_tool()


def run(*args: str) -> int:
    return subprocess.run([sys.executable, str(TOOL), *args], cwd=ROOT).returncode


def main(argv: list[str]) -> int:
    if len(argv) == 2 and argv[0] == "--french-metadata":
        out = Path(argv[1])
        out.mkdir(parents=True, exist_ok=True)
        for name in METADATA:
            (out / name).write_text(metadata_text(name, french=True), encoding="utf-8")
            print(f"wrote {out / name}")
        return 0
    if argv not in ([], ["--check"]):
        print(__doc__, file=sys.stderr)
        return 2
    if argv == ["--check"]:
        failed = run("vendor", "--dest", str(TOOL.parent), "--check")
        failed |= run(
            "check",
            *map(str, CATALOGS),
            "--gen",
            f"rust:{RUST}",
            "--gen",
            f"po:{PO}",
            *OPTS,
        )
        if not failed and ACCESSORS.read_text(encoding="utf-8") != accessor_test():
            print(f"{ACCESSORS.relative_to(ROOT)} differs from what the catalog produces (run scripts/gen-l10n.py)")
            failed = 1
        for name in METADATA:
            if not failed and (DATA / name).read_text(encoding="utf-8") != metadata_text(name, french=False):
                print(f"{(DATA / name).relative_to(ROOT)} differs from what its template and the catalog produce (run scripts/gen-l10n.py)")
                failed = 1
        return 1 if failed else 0
    catalogs = [str(path) for path in CATALOGS]
    failed = run("fmt", *catalogs)
    failed |= run(
        "gen", "--backend", "rust", "--out", str(RUST), "--opt", OPTS[1], "--opt", OPTS[5], *catalogs
    )
    failed |= run("gen", "--backend", "po", "--out", str(PO), "--opt", OPTS[3], *catalogs)
    if not failed:
        ACCESSORS.parent.mkdir(parents=True, exist_ok=True)
        ACCESSORS.write_text(accessor_test(), encoding="utf-8")
        for name in METADATA:
            (DATA / name).write_text(metadata_text(name, french=False), encoding="utf-8")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
